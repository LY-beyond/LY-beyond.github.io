/* =========================================================
 * data/sim-model.js —— 模拟器的公开线性模型（原样内联进 data.js）
 * ---------------------------------------------------------
 * 为什么单独一个文件：其他地方（产业规模、地图、图谱…）都是纯数据，能放进 CSV；
 * 唯独这里是一个函数 ——
 *   · 模拟器的四个滑块 → 五项输出的换算
 *   · 龙卷风敏感性图（一次只动一个因素）
 *   · 蒙特卡洛分布（四个一起小幅扰动）
 * 三处共用这同一个 model()，所以「旋钮位置 → 结果」在图与数之间永远一致。
 *
 * data/build.mjs 会把本文件的内容（去掉这行注释以上的说明）原样写进 data.js 的
 * sim.model 字段。本文件本身**不是模块、也不被执行**，只当文本片段用。
 * 改模型请改这里，然后跑 `node data/build.mjs`。
 * ========================================================= */
function (v) {
  var p = (v.penetration || 0) / 100;
  var d = (v.dataFactor || 0) / 100;
  var t = (v.talent || 0) / 100;
  var r = (v.rd || 0) / 100;
  var tfp = 0.20 + 0.55 * p + 0.30 * d + 0.35 * t + 0.30 * r;
  return {
    tfp: tfp,
    gdp: tfp * 1.5,
    cost: 3 + 13 * p + 5 * t,
    green: 2 + 9 * p + 7 * r,
    jobs: 15 + 120 * p + 60 * t,
    index: Math.round((0.40 * p + 0.20 * d + 0.20 * t + 0.20 * r) * 100)
  };
}
